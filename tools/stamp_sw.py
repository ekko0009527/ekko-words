"""Stamp sw.js with cache versions. Run from the repo root before deploying
(the GitHub Pages workflow runs it too):
    python tools/stamp_sw.py

- `const VERSION = "...";` is a hash of the app shell (HTML/CSS/JS/words.json/
  manifest/icons). Any change gives a new shell cache and an "update" prompt.
- The block between AUDIO:BEGIN / AUDIO:END maps every audio/*.mp3 to a hash of
  its own bytes. The service worker keeps one long-lived audio cache keyed by
  these hashes, so an update only downloads clips that are new or changed.
"""
import hashlib
import json
import re
from pathlib import Path

FILES = ["index.html", "css/style.css", "js/app.js", "words.json", "manifest.webmanifest"]
DIRS = ["icons"]
HASH_LEN = 12


def main():
    h = hashlib.sha256()
    paths = [Path(f) for f in FILES]
    for d in DIRS:
        paths += sorted(p for p in Path(d).rglob("*") if p.is_file())
    for p in paths:
        h.update(p.as_posix().encode() + b"\0" + p.read_bytes() + b"\0")
    version = h.hexdigest()[:HASH_LEN]

    audio = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()[:HASH_LEN]
             for p in sorted(Path("audio").glob("*.mp3"))}
    words = json.loads(Path("words.json").read_text(encoding="utf-8"))
    missing = [n for w in words for n in (f"{w['id']}.mp3", f"{w['id']}-ex.mp3") if n not in audio]
    if missing:
        raise SystemExit(f"words.json refers to missing audio files: {missing}")

    sw = Path("sw.js")
    text = sw.read_text(encoding="utf-8")
    new, n = re.subn(r'const VERSION = "[^"]*";', f'const VERSION = "{version}";', text, count=1)
    if n != 1:
        raise SystemExit("VERSION line not found in sw.js")
    body = ",\n".join(f'  "{k}": "{v}"' for k, v in audio.items())
    block = f"/* AUDIO:BEGIN (generated by tools/stamp_sw.py) */\nconst AUDIO = {{\n{body}\n}};\n/* AUDIO:END */"
    new, n = re.subn(r"/\* AUDIO:BEGIN.*?/\* AUDIO:END \*/", lambda m: block, new, count=1, flags=re.S)
    if n != 1:
        raise SystemExit("AUDIO:BEGIN / AUDIO:END block not found in sw.js")
    if new != text:
        sw.write_text(new, encoding="utf-8", newline="\n")
    print(f"sw.js VERSION = {version}, audio clips = {len(audio)}")


if __name__ == "__main__":
    main()
